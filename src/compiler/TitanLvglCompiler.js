'use strict';

/**
 * ⚡ TITAN LVGL / THORVG COMPILER (TitanLvglCompiler.js)
 * ─────────────────────────────────────────────────────────────
 * Direct Single-Pass Generator: Converts Shared JSX VNodes directly
 * into Native C++ (LVGL 9 & Samsung ThorVG Canvas) Screen Code.
 * Zero JavaScript on embedded hardware • 100% Deterministic Pure C++
 */

class TitanLvglCompiler {
  constructor() {
    this.varCounter = 0;
  }

  compileToCpp(vnode, screenName = 'MainScreen') {
    this.varCounter = 0;
    const bodyLines = [];
    const registerHooks = [];

    bodyLines.push(`    lv_obj_t* screen = lv_scr_act();`);
    bodyLines.push(`    lv_obj_set_style_bg_color(screen, lv_color_hex(0x020617), LV_PART_MAIN);`);
    bodyLines.push(`    lv_obj_set_style_pad_all(screen, 16, LV_PART_MAIN);`);

    this._compileElement(vnode, 'screen', bodyLines, registerHooks);

    return `/**
 * 🦚 Generated by Danphe-Native LVGL Engine
 * Architecture: 100% Native LVGL 9 + Samsung ThorVG Vector Canvas
 * Hardware Nervous System: Titan-Bus 16-Bit Register Serial Direct Map
 */

#include <iostream>
#include <string>
#include <lvgl.h>

#if LV_USE_THORVG
#include <thorvg.h>
using namespace tvg;
#endif

// Titan Bus In-Memory Serial Transceiver
extern "C" void titan_bus_subscribe(uint16_t reg_addr, void (*callback)(uint16_t reg, int16_t val, void* user_data), void* user_data);
extern "C" void titan_bus_write(uint16_t reg_addr, int16_t val);

extern "C" {
void danphe_init_${screenName}() {
${bodyLines.join('\n')}

    // 📡 Titan-Bus 16-Bit Register Direct Hook Wireups
${registerHooks.join('\n')}
}
}
`;
  }

  _compileElement(vnode, parentVar, lines, hooks) {
    if (!vnode) return;

    if (typeof vnode === 'string' || typeof vnode === 'number') {
      const lblVar = `lbl_${++this.varCounter}`;
      lines.push(`    lv_obj_t* ${lblVar} = lv_label_create(${parentVar});`);
      lines.push(`    lv_label_set_text(${lblVar}, "${this._escapeCpp(String(vnode))}");`);
      lines.push(`    lv_obj_set_style_text_color(${lblVar}, lv_color_hex(0xf8fafc), LV_PART_MAIN);`);
      return;
    }

    if (Array.isArray(vnode)) {
      for (const child of vnode) {
        this._compileElement(child, parentVar, lines, hooks);
      }
      return;
    }

    const tag = String(vnode.tag || vnode.type || 'div').toLowerCase();
    const props = vnode.props || {};

    // 🎯 TARGET FILTER: Skip web-only or mobile-only elements for embedded C++
    const target = String(props.target || props.platform || '').toLowerCase().trim();
    if (target === 'web' || target === 'browser' || target === 'mobile' || target === 'android' || tag === 'webonly' || tag === 'mobileonly') return;

    // 🛡️ PIPE FILTER: Strip out pipe styles
    if (props.className && typeof props.className === 'string') {
      props.className = props.className.replace(/\|[\s\S]*?\|/g, ' ').replace(/\s+/g, ' ').trim();
    }

    const children = vnode.children || (vnode.text ? [vnode.text] : []);

    // 1. Text / Heading
    if (['text', 'p', 'span', 'label', 'h1', 'h2', 'h3', 'h4', 'heading', 'title'].includes(tag)) {
      const lblVar = `lbl_${++this.varCounter}`;
      lines.push(`    lv_obj_t* ${lblVar} = lv_label_create(${parentVar});`);
      const txt = (children && children.length > 0 && typeof children[0] === 'string') ? children[0] : (props.text || '');
      lines.push(`    lv_label_set_text(${lblVar}, "${this._escapeCpp(txt)}");`);
      lines.push(`    lv_obj_set_style_text_color(${lblVar}, lv_color_hex(0x38bdf8), LV_PART_MAIN);`);

      // 16-Bit Register RX binding: rx={1005}
      const rxAddr = props.rx !== undefined ? props.rx : props['data-rx'];
      if (rxAddr !== undefined) {
        hooks.push(`    titan_bus_subscribe(${rxAddr}, [](uint16_t reg, int16_t val, void* user_data) {`);
        hooks.push(`        lv_obj_t* target_lbl = (lv_obj_t*)user_data;`);
        hooks.push(`        lv_label_set_text_fmt(target_lbl, "%d", val);`);
        hooks.push(`    }, ${lblVar});`);
      }
      return;
    }

    // 2. Button
    if (['button', 'btn'].includes(tag)) {
      const btnVar = `btn_${++this.varCounter}`;
      const btnLblVar = `btn_lbl_${++this.varCounter}`;
      lines.push(`    lv_obj_t* ${btnVar} = lv_btn_create(${parentVar});`);
      lines.push(`    lv_obj_set_style_bg_color(${btnVar}, lv_color_hex(0x0284c7), LV_PART_MAIN);`);
      lines.push(`    lv_obj_set_style_radius(${btnVar}, 8, LV_PART_MAIN);`);
      lines.push(`    lv_obj_t* ${btnLblVar} = lv_label_create(${btnVar});`);
      const txt = (children && children.length > 0 && typeof children[0] === 'string') ? children[0] : 'Click';
      lines.push(`    lv_label_set_text(${btnLblVar}, "${this._escapeCpp(txt)}");`);
      lines.push(`    lv_obj_center(${btnLblVar});`);

      // 16-Bit Register TX binding: tx={1}
      const txAddr = props.tx !== undefined ? props.tx : props['data-tx'];
      if (txAddr !== undefined) {
        hooks.push(`    lv_obj_add_event_cb(${btnVar}, [](lv_event_t* e) {`);
        hooks.push(`        titan_bus_write(${txAddr}, 1);`);
        hooks.push(`    }, LV_EVENT_CLICKED, NULL);`);
      }
      return;
    }

    // 3. Slider
    if (['slider', 'range'].includes(tag)) {
      const sldVar = `sld_${++this.varCounter}`;
      lines.push(`    lv_obj_t* ${sldVar} = lv_slider_create(${parentVar});`);
      lines.push(`    lv_slider_set_range(${sldVar}, ${props.min || 0}, ${props.max || 100});`);
      lines.push(`    lv_obj_set_style_bg_color(${sldVar}, lv_color_hex(0x38bdf8), LV_PART_INDICATOR);`);

      const txAddr = props.tx !== undefined ? props.tx : props.address;
      if (txAddr !== undefined) {
        hooks.push(`    lv_obj_add_event_cb(${sldVar}, [](lv_event_t* e) {`);
        hooks.push(`        lv_obj_t* slider = lv_event_get_target(e);`);
        hooks.push(`        int32_t val = lv_slider_get_value(slider);`);
        hooks.push(`        titan_bus_write(${txAddr}, (int16_t)val);`);
        hooks.push(`    }, LV_EVENT_VALUE_CHANGED, NULL);`);
      }
      return;
    }

    // 4. Auto-Layout Containers (vstack, hstack, row, column, container, card)
    const objVar = `obj_${++this.varCounter}`;
    lines.push(`    lv_obj_t* ${objVar} = lv_obj_create(${parentVar});`);
    lines.push(`    lv_obj_set_size(${objVar}, LV_PCT(100), LV_SIZE_CONTENT);`);
    lines.push(`    lv_obj_set_style_bg_color(${objVar}, lv_color_hex(0x0f172a), LV_PART_MAIN);`);
    lines.push(`    lv_obj_set_style_border_color(${objVar}, lv_color_hex(0x1e293b), LV_PART_MAIN);`);
    lines.push(`    lv_obj_set_style_radius(${objVar}, 8, LV_PART_MAIN);`);

    if (tag === 'vstack' || tag === 'column') {
      lines.push(`    lv_obj_set_flex_flow(${objVar}, LV_FLEX_FLOW_COLUMN);`);
      const gap = props.gap !== undefined ? (typeof props.gap === 'number' ? props.gap * 4 : 8) : 8;
      lines.push(`    lv_obj_set_style_pad_row(${objVar}, ${gap}, LV_PART_MAIN);`);
    } else if (tag === 'hstack' || tag === 'row') {
      lines.push(`    lv_obj_set_flex_flow(${objVar}, LV_FLEX_FLOW_ROW);`);
      const gap = props.gap !== undefined ? (typeof props.gap === 'number' ? props.gap * 4 : 8) : 8;
      lines.push(`    lv_obj_set_style_pad_column(${objVar}, ${gap}, LV_PART_MAIN);`);
    }

    // Compile nested children into this container
    if (Array.isArray(children)) {
      for (const child of children) {
        this._compileElement(child, objVar, lines, hooks);
      }
    }
  }

  _escapeCpp(str) {
    return str.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n');
  }
}

module.exports = TitanLvglCompiler;
