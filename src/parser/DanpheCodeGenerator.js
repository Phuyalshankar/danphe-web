'use strict';

/**
 * ⚡ DANPHE CODE GENERATOR & AST TRANSFORMER (DanpheCodeGenerator.js)
 * ─────────────────────────────────────────────────────────────
 * Multi-target code generator that transforms Danphe AST into:
 *   1. High-Performance Web JS (`h(tag, props, ...children)`)
 *   2. Server-Side Static HTML5 (`toHTML()`)
 *   3. Dolphin Intermediate Representation (`toDolphinIR()`)
 * ─────────────────────────────────────────────────────────────
 */

class DanpheCodeGenerator {
  /**
   * Generates production JavaScript for Web runtime from AST
   */
  static toWebJS(node) {
    if (!node) return '';

    switch (node.type) {
      case 'Program': {
        const preamble = `var _g = typeof globalThis !== 'undefined' ? globalThis : (typeof window !== 'undefined' ? window : (typeof global !== 'undefined' ? global : {}));\nvar _tw = (typeof TitanWidgets !== 'undefined' ? TitanWidgets : (_g.TitanWidgets || {}));`;
        const bodyCode = node.body.map(stmt => DanpheCodeGenerator.toWebJS(stmt)).join('\n\n');
        return `// 🏔️ Generated by Danphe World-Class Compiler\n${preamble}\n\n${bodyCode}`;
      }

      case 'RegisterDeclaration': {
        const fieldsList = JSON.stringify(node.fields);
        return `const ${node.id} = (typeof TitanRegisters !== 'undefined' ? TitanRegisters : require('../registers/TitanRegisters')).reg('reg ${node.id}:: ${node.fields.join(', ')};');`;
      }

      case 'FunctionDeclaration': {
        const params = node.params.join(', ');
        const bodyCode = node.body.map(b => DanpheCodeGenerator.toWebJS(b)).join('\n  ');
        let fnStr = `function ${node.id}(${params}) {\n  ${bodyCode}\n}`;
        if (node.isDefault) {
          fnStr += `\nmodule.exports = ${node.id};\nmodule.exports.default = ${node.id};`;
        } else if (node.isExported) {
          fnStr += `\nexports.${node.id} = ${node.id};`;
        }
        return fnStr;
      }

      case 'ReturnStatement': {
        const argCode = node.argument ? DanpheCodeGenerator.toWebJS(node.argument) : 'null';
        return `return ${argCode};`;
      }

      case 'JSXElement': {
        const tag = /^[A-Z]/.test(node.tag)
          ? `(typeof ${node.tag} !== 'undefined' ? ${node.tag} : (_tw.${node.tag} || ${JSON.stringify(node.tag)}))`
          : JSON.stringify(node.tag);
        const propsObj = DanpheCodeGenerator._generatePropsJS(node.props);
        const childrenArr = node.children.map(c => DanpheCodeGenerator.toWebJS(c));

        if (childrenArr.length === 0) {
          return `h(${tag}, ${propsObj})`;
        }
        return `h(${tag}, ${propsObj}, ${childrenArr.join(', ')})`;
      }

      case 'JSXFragment': {
        const childrenArr = node.children.map(c => DanpheCodeGenerator.toWebJS(c));
        if (childrenArr.length === 0) {
          return `h(Fragment, null)`;
        }
        return `h(Fragment, null, ${childrenArr.join(', ')})`;
      }

      case 'JSXText': {
        return JSON.stringify(node.value);
      }

      case 'JSXExpression': {
        return DanpheCodeGenerator.toWebJS(node.expression);
      }

      case 'Literal': {
        return typeof node.value === 'string' ? JSON.stringify(node.value) : String(node.value);
      }

      case 'Identifier': {
        return node.name;
      }

      case 'MemberExpression': {
        const obj = DanpheCodeGenerator.toWebJS(node.object);
        const prop = DanpheCodeGenerator.toWebJS(node.property);
        return node.computed ? `${obj}[${prop}]` : `${obj}.${prop}`;
      }

      case 'CallExpression': {
        const callee = DanpheCodeGenerator.toWebJS(node.callee);
        const args = node.args.map(a => DanpheCodeGenerator.toWebJS(a)).join(', ');
        return `${callee}(${args})`;
      }

      case 'BinaryExpression': {
        const left = DanpheCodeGenerator.toWebJS(node.left);
        const right = DanpheCodeGenerator.toWebJS(node.right);
        return `(${left} ${node.operator} ${right})`;
      }

      case 'UnaryExpression': {
        const arg = DanpheCodeGenerator.toWebJS(node.argument);
        return `${node.operator}(${arg})`;
      }

      case 'ConditionalExpression': {
        const test = DanpheCodeGenerator.toWebJS(node.test);
        const cons = DanpheCodeGenerator.toWebJS(node.consequent);
        const alt = DanpheCodeGenerator.toWebJS(node.alternate);
        return `(${test} ? ${cons} : ${alt})`;
      }

      case 'ArrowFunctionExpression': {
        const params = (node.params || []).map(p => DanpheCodeGenerator.toWebJS(p)).join(', ');
        const body = DanpheCodeGenerator.toWebJS(node.body);
        return `((${params}) => ${body})`;
      }

      case 'ObjectExpression': {
        const props = (node.properties || []).map(p => {
          const k = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(p.key) ? p.key : JSON.stringify(p.key);
          return `${k}: ${DanpheCodeGenerator.toWebJS(p.value)}`;
        }).join(', ');
        return `{ ${props} }`;
      }

      case 'ArrayExpression': {
        const elems = (node.elements || []).map(e => DanpheCodeGenerator.toWebJS(e)).join(', ');
        return `[${elems}]`;
      }

      default:
        return '';
    }
  }

  static _generatePropsJS(props) {
    if (!props || Object.keys(props).length === 0) return 'null';

    const entries = [];
    let hasSpread = false;

    for (const [key, val] of Object.entries(props)) {
      if (val && val.type === 'JSXSpreadAttribute') {
        hasSpread = true;
        entries.push(`...${DanpheCodeGenerator.toWebJS(val.argument)}`);
      } else {
        const k = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
        entries.push(`${k}: ${DanpheCodeGenerator.toWebJS(val)}`);
      }
    }

    return `{ ${entries.join(', ')} }`;
  }

  /**
   * Generates clean Server-Side Static HTML5 string directly from AST
   */
  static toHTML(node) {
    if (!node) return '';

    if (node.type === 'Program') {
      return node.body.map(stmt => DanpheCodeGenerator.toHTML(stmt)).join('');
    }

    if (node.type === 'FunctionDeclaration') {
      const ret = node.body.find(b => b.type === 'ReturnStatement');
      return ret ? DanpheCodeGenerator.toHTML(ret.argument) : '';
    }

    if (node.type === 'ReturnStatement') {
      return DanpheCodeGenerator.toHTML(node.argument);
    }

    if (node.type === 'JSXText') {
      return DanpheCodeGenerator._escapeHTML(node.value);
    }

    if (node.type === 'Literal') {
      return DanpheCodeGenerator._escapeHTML(String(node.value));
    }

    if (node.type === 'JSXFragment') {
      return (node.children || []).map(c => DanpheCodeGenerator.toHTML(c)).join('');
    }

    if (node.type === 'JSXElement') {
      const isCustomComponent = /^[A-Z]/.test(node.tag);
      const tag = isCustomComponent ? node.tag : node.tag.toLowerCase();
      let attrs = '';

      if (node.props) {
        for (const [key, val] of Object.entries(node.props)) {
          if (val && val.type === 'JSXSpreadAttribute') continue;
          let attrVal = '';
          if (val && val.type === 'Literal') {
            attrVal = String(val.value);
          }
          const htmlKey = key === 'className' ? 'class' : key;
          attrs += ` ${htmlKey}="${DanpheCodeGenerator._escapeHTML(attrVal)}"`;
        }
      }

      const inner = (node.children || []).map(c => DanpheCodeGenerator.toHTML(c)).join('');
      const selfClosingTags = new Set(['input', 'img', 'br', 'hr', 'meta', 'link']);
      if (selfClosingTags.has(tag) && !inner) {
        return `<${tag}${attrs} />`;
      }
      return `<${tag}${attrs}>${inner}</${tag}>`;
    }

    return '';
  }

  static _escapeHTML(str) {
    return String(str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }

  /**
   * Generates Dolphin Intermediate Representation (IR) tree for Native compilers
   */
  static toDolphinIR(node) {
    if (!node) return null;

    if (node.type === 'Program') {
      const children = node.body.map(stmt => DanpheCodeGenerator.toDolphinIR(stmt)).filter(Boolean);
      return { type: 'DolphinApp', children };
    }

    if (node.type === 'FunctionDeclaration') {
      const ret = node.body.find(b => b.type === 'ReturnStatement');
      return ret ? DanpheCodeGenerator.toDolphinIR(ret.argument) : null;
    }

    if (node.type === 'ReturnStatement') {
      return DanpheCodeGenerator.toDolphinIR(node.argument);
    }

    if (node.type === 'JSXElement') {
      const rawProps = {};
      if (node.props) {
        for (const [k, v] of Object.entries(node.props)) {
          if (v && v.type === 'Literal') rawProps[k] = v.value;
        }
      }
      const children = (node.children || []).map(c => DanpheCodeGenerator.toDolphinIR(c)).filter(Boolean);
      return {
        tag: node.tag,
        props: rawProps,
        children: children
      };
    }

    if (node.type === 'JSXText') {
      return { tag: 'Text', text: node.value };
    }

    return null;
  }
}

module.exports = {
  DanpheCodeGenerator
};
